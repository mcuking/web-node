const inverse = (table: Uint8Array): Uint8Array => {
  const out = new Uint8Array(256);
  for (let i = 0; i < 256; i++) out[table[i]] = i;
  return out;
};
const SB3 = inverse(SB1);
const SB4 = inverse(SB2);

const C1 = 0x517cc1b727220a94fe13abe8fa9a6ee0n;
const C2 = 0x6db14acc9e21c820ff28b1d5ef5de2b0n;
const C3 = 0xdb92371d2126e9700324977504e8c90en;
const MASK128 = (1n << 128n) - 1n;

const rotr128 = (x: bigint, n: number): bigint => ((x >> BigInt(n)) | (x << BigInt(128 - n))) & MASK128;
const rotl128 = (x: bigint, n: number): bigint => ((x << BigInt(n)) | (x >> BigInt(128 - n))) & MASK128;

function toBytes(value: bigint): Uint8Array<ArrayBuffer> {
  const out = new Uint8Array(16);
  let v = value;
  for (let i = 15; i >= 0; i--) {
    out[i] = Number(v & 0xffn);
    v >>= 8n;
  }
  return out;
}

function toBig(bytes: Uint8Array, offset = 0): bigint {
  let out = 0n;
  for (let i = 0; i < 16; i++) out = (out << 8n) | BigInt(bytes[offset + i]);
  return out;
}

/** The diffusion layer A (§2.4.3), an involution. */
function diffuse(x: Uint8Array): Uint8Array<ArrayBuffer> {
  const y = new Uint8Array(16);
  y[0] = x[3] ^ x[4] ^ x[6] ^ x[8] ^ x[9] ^ x[13] ^ x[14];
  y[1] = x[2] ^ x[5] ^ x[7] ^ x[8] ^ x[9] ^ x[12] ^ x[15];
  y[2] = x[1] ^ x[4] ^ x[6] ^ x[10] ^ x[11] ^ x[12] ^ x[15];
  y[3] = x[0] ^ x[5] ^ x[7] ^ x[10] ^ x[11] ^ x[13] ^ x[14];
  y[4] = x[0] ^ x[2] ^ x[5] ^ x[8] ^ x[11] ^ x[14] ^ x[15];
  y[5] = x[1] ^ x[3] ^ x[4] ^ x[9] ^ x[10] ^ x[14] ^ x[15];
  y[6] = x[0] ^ x[2] ^ x[7] ^ x[9] ^ x[10] ^ x[12] ^ x[13];
  y[7] = x[1] ^ x[3] ^ x[6] ^ x[8] ^ x[11] ^ x[12] ^ x[13];
  y[8] = x[0] ^ x[1] ^ x[4] ^ x[7] ^ x[10] ^ x[13] ^ x[15];
  y[9] = x[0] ^ x[1] ^ x[5] ^ x[6] ^ x[11] ^ x[12] ^ x[14];
  y[10] = x[2] ^ x[3] ^ x[5] ^ x[6] ^ x[8] ^ x[13] ^ x[15];
  y[11] = x[2] ^ x[3] ^ x[4] ^ x[7] ^ x[9] ^ x[12] ^ x[14];
  y[12] = x[1] ^ x[2] ^ x[6] ^ x[7] ^ x[9] ^ x[11] ^ x[12];
  y[13] = x[0] ^ x[3] ^ x[6] ^ x[7] ^ x[8] ^ x[10] ^ x[13];
  y[14] = x[0] ^ x[3] ^ x[4] ^ x[5] ^ x[9] ^ x[11] ^ x[14];
  y[15] = x[1] ^ x[2] ^ x[4] ^ x[5] ^ x[8] ^ x[10] ^ x[15];
  return y;
}

/** SL1 (§2.4.2): SB1, SB2, SB3, SB4 cycling over the bytes. */
function sl1(x: Uint8Array): Uint8Array<ArrayBuffer> {
  const y = new Uint8Array(16);
  for (let i = 0; i < 16; i++) {
    const box = i % 4;
    y[i] = box === 0 ? SB1[x[i]] : box === 1 ? SB2[x[i]] : box === 2 ? SB3[x[i]] : SB4[x[i]];
  }
  return y;
}

/** SL2 (§2.4.2): SB3, SB4, SB1, SB2 cycling over the bytes (the inverse of SL1). */
function sl2(x: Uint8Array): Uint8Array<ArrayBuffer> {
  const y = new Uint8Array(16);
  for (let i = 0; i < 16; i++) {
    const box = i % 4;
    y[i] = box === 0 ? SB3[x[i]] : box === 1 ? SB4[x[i]] : box === 2 ? SB1[x[i]] : SB2[x[i]];
  }
  return y;
}

const xor = (a: Uint8Array, b: Uint8Array): Uint8Array<ArrayBuffer> => {
  const out = new Uint8Array(16);
  for (let i = 0; i < 16; i++) out[i] = a[i] ^ b[i];
  return out;
};

/** FO(D, RK) = A(SL1(D ^ RK)). */
const fo = (d: Uint8Array, rk: Uint8Array): Uint8Array<ArrayBuffer> => diffuse(sl1(xor(d, rk)));

/** FE(D, RK) = A(SL2(D ^ RK)). */
const fe = (d: Uint8Array, rk: Uint8Array): Uint8Array<ArrayBuffer> => diffuse(sl2(xor(d, rk)));

export class Aria {
  #ek: Uint8Array[];
  #dk: Uint8Array[];
  #rounds: number;

  constructor(key: Uint8Array) {
    if (key.length !== 16 && key.length !== 24 && key.length !== 32) {
      throw new Error('Invalid key length');
    }
    const rounds = key.length === 16 ? 12 : key.length === 24 ? 14 : 16;
    const cks =
      key.length === 16
        ? [C1, C2, C3]
        : key.length === 24
          ? [C2, C3, C1]
          : [C3, C1, C2];

    let KL = 0n;
    for (let i = 0; i < 16; i++) KL = (KL << 8n) | BigInt(key[i]);
    let KR = 0n;
    for (let i = 16; i < key.length; i++) KR = (KR << 8n) | BigInt(key[i]);
    KR <<= BigInt((32 - key.length) * 8);

    const w0 = KL;
    const w1 = toBig(fo(toBytes(w0), toBytes(cks[0]))) ^ KR;
    const w2 = toBig(fe(toBytes(w1), toBytes(cks[1]))) ^ w0;
    const w3 = toBig(fo(toBytes(w2), toBytes(cks[2]))) ^ w1;

    const ek: bigint[] = [];
    ek[1] = w0 ^ rotr128(w1, 19);
    ek[2] = w1 ^ rotr128(w2, 19);
    ek[3] = w2 ^ rotr128(w3, 19);
    ek[4] = rotr128(w0, 19) ^ w3;
    ek[5] = w0 ^ rotr128(w1, 31);
    ek[6] = w1 ^ rotr128(w2, 31);
    ek[7] = w2 ^ rotr128(w3, 31);
    ek[8] = rotr128(w0, 31) ^ w3;
    ek[9] = w0 ^ rotl128(w1, 61);
    ek[10] = w1 ^ rotl128(w2, 61);
    ek[11] = w2 ^ rotl128(w3, 61);
    ek[12] = rotl128(w0, 61) ^ w3;
    ek[13] = w0 ^ rotl128(w1, 31);
    ek[14] = w1 ^ rotl128(w2, 31);
    ek[15] = w2 ^ rotl128(w3, 31);
    ek[16] = rotl128(w0, 31) ^ w3;
    ek[17] = w0 ^ rotl128(w1, 19);

    // Decryption keys: dk1 = ek{n+1}, dk{i} = A(ek{n+2-i}) for 2 <= i <= n,
    // dk{n+1} = ek1 (§2.2).
    const dk: bigint[] = [];
    dk[1] = ek[rounds + 1];
    for (let i = 2; i <= rounds; i++) dk[i] = toBig(diffuse(toBytes(ek[rounds + 2 - i])));
    dk[rounds + 1] = ek[1];

    this.#ek = ek.map(toBytes) as Uint8Array<ArrayBuffer>[];
    this.#dk = dk.map(toBytes) as Uint8Array<ArrayBuffer>[];
    this.#rounds = rounds;
  }

  #crypt(block: Uint8Array, keys: Uint8Array[]): void {
    let d = block.slice();
    for (let round = 1; round < this.#rounds; round++) {
      d = round % 2 === 1 ? fo(d, keys[round]) : fe(d, keys[round]);
    }
    d = xor(sl2(xor(d, keys[this.#rounds])), keys[this.#rounds + 1]);
    block.set(d);
  }

  encryptBlock(block: Uint8Array): void {
    this.#crypt(block, this.#ek);
  }

  decryptBlock(block: Uint8Array): void {
    this.#crypt(block, this.#dk);
  }
}
